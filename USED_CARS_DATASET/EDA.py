import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
sns.set_style("whitegrid")
plt.rcParams['figure.figsize'] = (8,5)
df = pd.read_csv("used_cars_uncleaned_dataset.csv")
df.head()
print("Shape:", df.shape)
print("\nColumn names:", df.columns.tolist())
print("\nData types:\n", df.dtypes)
df.sample(5)
numerical_cols = ['Year', 'Kilometers_Driven', 'Owner', 'Engine_CC', 'Mileage_kmpl', 'Price_INR']
categorical_cols = ['Brand', 'Model', 'Fuel_Type', 'Transmission', 'City']
print("Numerical columns:", numerical_cols)
print("Categorical columns:", categorical_cols)
print("Missing values per column:\n", df.isnull().sum())
print("\nNumber of duplicate rows:", df.duplicated().sum())
print("\nUnique Brand values:", sorted(df['Brand'].unique()))
print("Unique Fuel_Type values:", df['Fuel_Type'].unique())
print("Unique Transmission values:", df['Transmission'].unique())
print("Unique City values:", df['City'].unique())
rows_before = df.shape[0]
print("Rows before cleaning:", rows_before)
df['Brand'] = df['Brand'].str.strip().str.title()
df['Fuel_Type'] = df['Fuel_Type'].str.strip().str.title()
df['Transmission'] = df['Transmission'].str.strip().str.title()
df['City'] = df['City'].str.strip().str.title()
print("Brand after cleaning:", sorted(df['Brand'].dropna().unique()))
print("Fuel_Type after cleaning:", df['Fuel_Type'].dropna().unique())
print("Transmission after cleaning:", df['Transmission'].dropna().unique())
print("City after cleaning:", df['City'].dropna().unique())
df = df.drop_duplicates()
print("Rows after removing duplicates:", df.shape[0])
for col in ['Fuel_Type', 'Transmission', 'City']:
    mode_val = df[col].mode()[0]
    df[col] = df[col].fillna(mode_val)
for col in ['Engine_CC', 'Mileage_kmpl']:
    median_val = df[col].median()
    df[col] = df[col].fillna(median_val)
print("Missing values after cleaning:\n", df.isnull().sum())
rows_after = df.shape[0]
print(f"Rows before cleaning: {rows_before}")
print(f"Rows after cleaning: {rows_after}")
print(f"Rows removed: {rows_before - rows_after}")
current_year = 2026
df['Car_Age'] = current_year - df['Year']
print(df[['Year','Car_Age']].head())
print(df[numerical_cols].describe())
for col in categorical_cols:
    print(f"\n--- {col} ---")
    print(df[col].value_counts())
def count_outliers(col):
    Q1 = df[col].quantile(0.25)
    Q3 = df[col].quantile(0.75)
    IQR = Q3 - Q1
    lower = Q1 - 1.5 * IQR
    upper = Q3 + 1.5 * IQR
    outliers = df[(df[col] < lower) | (df[col] > upper)]
    print(f"{col}: {len(outliers)} outliers (bounds: {lower:.0f} to {upper:.0f})")
    return outliers
price_outliers = count_outliers('Price_INR')
km_outliers = count_outliers('Kilometers_Driven')
